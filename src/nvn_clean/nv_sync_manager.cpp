void SyncManager::InitializeGpuQueryResources() {
    constexpr VkDeviceSize kRawResultsBytes =
        static_cast<VkDeviceSize>(kRawQueryResultRingCapacity) * sizeof(u64);
    constexpr VkDeviceSize kQueueAccumulatorsBytes =
        Common::AlignUp(static_cast<VkDeviceSize>(kMaxNvnQueues) * sizeof(u64), 256);
    constexpr VkDeviceSize kResolveOpsRingBytes =
        static_cast<VkDeviceSize>(kQueryResolveRingCapacity) * sizeof(GpuQueryResolveOp);
    constexpr VkDeviceSize kPredicateRingBytes =
        static_cast<VkDeviceSize>(kConditionalPredicateSlots) * kPredicateSlotStrideBytes;

    const VkBufferUsageFlags base_ssbo_usage =
        VK_BUFFER_USAGE_STORAGE_BUFFER_BIT | VK_BUFFER_USAGE_TRANSFER_DST_BIT |
        VK_BUFFER_USAGE_TRANSFER_SRC_BIT;

    VkBufferUsageFlags predicate_usage = base_ssbo_usage;
    if (device_.IsExtConditionalRendering()) {
        predicate_usage |= VK_BUFFER_USAGE_CONDITIONAL_RENDERING_BIT_EXT;
    }

    const bool ok_raw = AllocateVmaInternalBuffer(
        device_, allocator_, kRawResultsBytes, base_ssbo_usage, false, false,
        "NvnClean::RawQueryResults", &raw_query_results_buffer_.device_address,
        &raw_query_results_buffer_.allocation, &raw_query_results_buffer_.mapped,
        &raw_query_results_buffer_.buffer);

    // Allocate queue accumulators & predicate ring in ReBAR (DEVICE_LOCAL | HOST_VISIBLE) so they
    // start deterministically zeroed without requiring a constructor command-buffer submission.
    const bool ok_acc = AllocateVmaInternalBuffer(
        device_, allocator_, kQueueAccumulatorsBytes, base_ssbo_usage, true, true,
        "NvnClean::QueueAccumulators", &queue_accumulators_buffer_.device_address,
        &queue_accumulators_buffer_.allocation, &queue_accumulators_buffer_.mapped,
        &queue_accumulators_buffer_.buffer);

    const bool ok_ops = AllocateVmaInternalBuffer(
        device_, allocator_, kResolveOpsRingBytes, base_ssbo_usage, true, false,
        "NvnClean::QueryResolveOpsRing", &resolve_ops_ring_buffer_.device_address,
        &resolve_ops_ring_buffer_.allocation, &resolve_ops_ring_buffer_.mapped,
        &resolve_ops_ring_buffer_.buffer);

    const bool ok_pred = AllocateVmaInternalBuffer(
        device_, allocator_, kPredicateRingBytes, predicate_usage, true, true,
        "NvnClean::ConditionalPredicateRing", &predicate_ring_buffer_.device_address,
        &predicate_ring_buffer_.allocation, &predicate_ring_buffer_.mapped,
        &predicate_ring_buffer_.buffer);

    if (!ok_raw || !ok_acc || !ok_ops || !ok_pred || resolve_ops_ring_buffer_.mapped.empty()) {
        LOG_ERROR(Render_Vulkan,
                  "[NvnClean] SyncManager failed to initialize GPU query resolve buffers");
        return;
    }

    const vk::Device& logical = device_.GetLogical();

    const std::array<VkDescriptorSetLayoutBinding, 4> bindings{{
        {
            .binding = 0,
            .descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER,
            .descriptorCount = 1,
            .stageFlags = VK_SHADER_STAGE_COMPUTE_BIT,
            .pImmutableSamplers = nullptr,
        },
        {
            .binding = 1,
            .descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER,
            .descriptorCount = 1,
            .stageFlags = VK_SHADER_STAGE_COMPUTE_BIT,
            .pImmutableSamplers = nullptr,
        },
        {
            .binding = 2,
            .descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER,
            .descriptorCount = 1,
            .stageFlags = VK_SHADER_STAGE_COMPUTE_BIT,
            .pImmutableSamplers = nullptr,
        },
        {
            .binding = 3,
            .descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER,
            .descriptorCount = 1,
            .stageFlags = VK_SHADER_STAGE_COMPUTE_BIT,
            .pImmutableSamplers = nullptr,
        },
    }};

    resolve_set_layout_ = logical.CreateDescriptorSetLayout(VkDescriptorSetLayoutCreateInfo{
        .sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_LAYOUT_CREATE_INFO,
        .pNext = nullptr,
        .flags = 0,
        .bindingCount = static_cast<u32>(bindings.size()),
        .pBindings = bindings.data(),
    });

    const VkDescriptorPoolSize pool_size{
        .type = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER,
        .descriptorCount = static_cast<u32>(bindings.size()),
    };
    resolve_descriptor_pool_ = logical.CreateDescriptorPool(VkDescriptorPoolCreateInfo{
        .sType = VK_STRUCTURE_TYPE_DESCRIPTOR_POOL_CREATE_INFO,
        .pNext = nullptr,
        .flags = 0,
        .maxSets = 1,
        .poolSizeCount = 1,
        .pPoolSizes = &pool_size,
    });

    const VkDescriptorSetAllocateInfo alloc_info{
        .sType = VK_STRUCTURE_TYPE_DESCRIPTOR_SET_ALLOCATE_INFO,
        .pNext = nullptr,
        .descriptorPool = *resolve_descriptor_pool_,
        .descriptorSetCount = 1,
        .pSetLayouts = resolve_set_layout_.address(),
    };
    if (dld_.vkAllocateDescriptorSets(*logical, &alloc_info, &resolve_descriptor_set_) !=
            VK_SUCCESS ||
        resolve_descriptor_set_ == VK_NULL_HANDLE) {
        LOG_ERROR(Render_Vulkan,
                  "[NvnClean] SyncManager failed to allocate query resolve descriptor set");
        return;
    }

    const std::array<VkDescriptorBufferInfo, 4> buffer_infos{{
        {
            .buffer = *raw_query_results_buffer_.buffer,
            .offset = 0,
            .range = VK_WHOLE_SIZE,
        },
        {
            .buffer = *queue_accumulators_buffer_.buffer,
            .offset = 0,
            .range = VK_WHOLE_SIZE,
        },
        {
            .buffer = *resolve_ops_ring_buffer_.buffer,
            .offset = 0,
            .range = VK_WHOLE_SIZE,
        },
        {
            .buffer = *predicate_ring_buffer_.buffer,
            .offset = 0,
            .range = VK_WHOLE_SIZE,
        },
    }};

    std::array<VkWriteDescriptorSet, 4> writes{};
    for (u32 i = 0; i < static_cast<u32>(writes.size()); ++i) {
        writes[i] = VkWriteDescriptorSet{
            .sType = VK_STRUCTURE_TYPE_WRITE_DESCRIPTOR_SET,
            .pNext = nullptr,
            .dstSet = resolve_descriptor_set_,
            .dstBinding = i,
            .dstArrayElement = 0,
            .descriptorCount = 1,
            .descriptorType = VK_DESCRIPTOR_TYPE_STORAGE_BUFFER,
            .pImageInfo = nullptr,
            .pBufferInfo = &buffer_infos[i],
            .pTexelBufferView = nullptr,
        };
    }
    logical.UpdateDescriptorSets(writes, {});

    const VkPushConstantRange push_range{
        .stageFlags = VK_SHADER_STAGE_COMPUTE_BIT,
        .offset = 0,
        .size = static_cast<u32>(sizeof(GpuQueryResolvePushConstants)),
    };
    resolve_pipeline_layout_ = logical.CreatePipelineLayout(VkPipelineLayoutCreateInfo{
        .sType = VK_STRUCTURE_TYPE_PIPELINE_LAYOUT_CREATE_INFO,
        .pNext = nullptr,
        .flags = 0,
        .setLayoutCount = 1,
        .pSetLayouts = resolve_set_layout_.address(),
        .pushConstantRangeCount = 1,
        .pPushConstantRanges = &push_range,
    });

    if (!device_.IsBufferDeviceAddressSupported()) {
        LOG_WARNING(Render_Vulkan,
                    "[NvnClean] VK_KHR_buffer_device_address disabled; skipping query resolve PSO");
        return;
    }

    const std::span<const u32> spirv_code =
        !config_.custom_resolve_spirv.empty()
            ? config_.custom_resolve_spirv
            : std::span<const u32>{kDefaultQueryResolveSpirv};

    try {
        resolve_shader_module_ = logical.CreateShaderModule(VkShaderModuleCreateInfo{
            .sType = VK_STRUCTURE_TYPE_SHADER_MODULE_CREATE_INFO,
            .pNext = nullptr,
            .flags = 0,
            .codeSize = spirv_code.size_bytes(),
            .pCode = spirv_code.data(),
        });
        resolve_shader_module_.SetObjectNameEXT("NvnClean::QueryResolveCS");

        resolve_pipeline_ = logical.CreateComputePipeline(
            VkComputePipelineCreateInfo{
                .sType = VK_STRUCTURE_TYPE_COMPUTE_PIPELINE_CREATE_INFO,
                .pNext = nullptr,
                .flags = 0,
                .stage =
                    VkPipelineShaderStageCreateInfo{
                        .sType = VK_STRUCTURE_TYPE_PIPELINE_SHADER_STAGE_CREATE_INFO,
                        .pNext = nullptr,
                        .flags = 0,
                        .stage = VK_SHADER_STAGE_COMPUTE_BIT,
                        .module = *resolve_shader_module_,
                        .pName = "main",
                        .pSpecializationInfo = nullptr,
                    },
                .layout = *resolve_pipeline_layout_,
                .basePipelineHandle = VK_NULL_HANDLE,
                .basePipelineIndex = 0,
            },
            device_.StaticPipelineCache());
        if (dld_.vkSetDebugUtilsObjectNameEXT != nullptr && resolve_pipeline_) {
            const VkDebugUtilsObjectNameInfoEXT name_info{
                .sType = VK_STRUCTURE_TYPE_DEBUG_UTILS_OBJECT_NAME_INFO_EXT,
                .pNext = nullptr,
                .objectType = VK_OBJECT_TYPE_PIPELINE,
                .objectHandle = reinterpret_cast<u64>(*resolve_pipeline_),
                .pObjectName = "NvnClean::QueryResolvePipeline",
            };
            dld_.vkSetDebugUtilsObjectNameEXT(*logical, &name_info);
        }
    } catch (const vk::Exception& ex) {
        LOG_ERROR(Render_Vulkan,
                  "[NvnClean] Failed to build GPU query resolve compute pipeline: {}", ex.what());
        resolve_pipeline_.reset();
        resolve_shader_module_.reset();
    }
}

// ================================================================================================
// Per-Queue Timeline Semaphores (`VK_KHR_timeline_semaphore` & `nvnSyncWait`)
// ================================================================================================

VkSemaphore SyncManager::QueueTimelineSemaphore(u32 queue_id) {
    if (queue_id >= kMaxNvnQueues) [[unlikely]] {
        LOG_ERROR(Render_Vulkan, "[NvnClean] Out-of-range NVN queue id {} (max {})", queue_id,
                  kMaxNvnQueues);
        return VK_NULL_HANDLE;
    }

    QueueTimelineSlot& slot = queue_timelines_[queue_id];
    VkSemaphore handle = slot.raw_handle.load(std::memory_order_acquire);
    if (handle != VK_NULL_HANDLE) [[likely]] {
        return handle;
    }

    std::lock_guard lock{slot.create_mutex};
    handle = slot.raw_handle.load(std::memory_order_relaxed);
    if (handle != VK_NULL_HANDLE) {
        return handle;
    }

    const VkSemaphoreTypeCreateInfo timeline_ci{
        .sType = VK_STRUCTURE_TYPE_SEMAPHORE_TYPE_CREATE_INFO,
        .pNext = nullptr,
        .semaphoreType = VK_SEMAPHORE_TYPE_TIMELINE,
        .initialValue = 0,
    };
    const VkSemaphoreCreateInfo sem_ci{
        .sType = VK_STRUCTURE_TYPE_SEMAPHORE_CREATE_INFO,
        .pNext = &timeline_ci,
        .flags = 0,
    };
    slot.semaphore = device_.GetLogical().CreateSemaphore(sem_ci);
    const std::string debug_name = fmt::format("NvnClean::QueueTimeline[{}]", queue_id);
    slot.semaphore.SetObjectNameEXT(debug_name.c_str());

    handle = *slot.semaphore;
    slot.raw_handle.store(handle, std::memory_order_release);
    return handle;
}

u64 SyncManager::AllocateNextTimelineValue(u32 queue_id) {
    if (queue_id >= kMaxNvnQueues) [[unlikely]] {
        return 0;
    }
    return queue_timelines_[queue_id].next_value.fetch_add(1, std::memory_order_relaxed);
}

VkSemaphoreSubmitInfo SyncManager::MakeTimelineSignalSubmitInfo(
    u32 queue_id, u64 timeline_value, VkPipelineStageFlags2 stage_mask) {
    const VkSemaphore sem = QueueTimelineSemaphore(queue_id);
    return VkSemaphoreSubmitInfo{
        .sType = VK_STRUCTURE_TYPE_SEMAPHORE_SUBMIT_INFO,
        .pNext = nullptr,
        .semaphore = sem,
        .value = timeline_value,
        .stageMask = stage_mask,
        .deviceIndex = 0,
    };
}

void SyncManager::NotifyTimelineSubmitted(u32 queue_id, u64 timeline_value) noexcept {
    if (queue_id >= kMaxNvnQueues || timeline_value == 0) [[unlikely]] {
        return;
    }
    MonotonicMaxStore(queue_timelines_[queue_id].submitted_value, timeline_value);
    timeline_submissions_.fetch_add(1, std::memory_order_relaxed);
}

u64 SyncManager::PollCompletedTimelineValue(u32 queue_id) noexcept {
    if (queue_id >= kMaxNvnQueues) [[unlikely]] {
        return 0;
    }

    QueueTimelineSlot& slot = queue_timelines_[queue_id];
    const u64 cached = slot.cached_completed_value.load(std::memory_order_acquire);
    const VkSemaphore sem = slot.raw_handle.load(std::memory_order_acquire);
    if (sem == VK_NULL_HANDLE) {
        return cached;
    }

    const u64 submitted = slot.submitted_value.load(std::memory_order_acquire);
    const u64 allocated = slot.next_value.load(std::memory_order_acquire) - 1ULL;
    const u64 upper_bound = (std::max)(submitted, allocated);
    if (cached >= upper_bound) {
        return cached;
    }

    u64 live_value = 0;
    if (dld_.vkGetSemaphoreCounterValue(*device_.GetLogical(), sem, &live_value) == VK_SUCCESS) {
        MonotonicMaxStore(slot.cached_completed_value, live_value);
        return (std::max)(cached, live_value);
    }
    return cached;
}

bool SyncManager::IsTimelineValueComplete(u32 queue_id, u64 timeline_value) noexcept {
    if (timeline_value == 0) {
        return true;
    }
    if (queue_id >= kMaxNvnQueues) [[unlikely]] {
        return false;
    }

    const QueueTimelineSlot& slot = queue_timelines_[queue_id];
    if (slot.cached_completed_value.load(std::memory_order_acquire) >= timeline_value) [[likely]] {
        return true;
    }
    return PollCompletedTimelineValue(queue_id) >= timeline_value;
}

void SyncManager::RecordFenceSync(u64 sync_serial, u32 queue_id, u64 signal_timeline_value,
                                  u32 condition, u32 flags) {
    if (sync_serial == 0 || queue_id >= kMaxNvnQueues) [[unlikely]] {
        return;
    }

    (void)QueueTimelineSemaphore(queue_id);

    {
        std::unique_lock lock{sync_table_mutex_};
        sync_points_[sync_serial] = TimelineSyncPoint{
            .queue_id = queue_id,
            .timeline_value = signal_timeline_value,
            .condition = condition,
            .flags = flags,
            .valid = (signal_timeline_value != 0),
        };
    }

    fence_syncs_recorded_.fetch_add(1, std::memory_order_relaxed);
}

void SyncManager::DestroySync(u64 sync_serial) noexcept {
    try {
        std::unique_lock lock{sync_table_mutex_};
        sync_points_.erase(sync_serial);
    } catch (...) {
    }
}

TimelineSyncPoint SyncManager::FindSyncPoint(u64 sync_serial) const noexcept {
    try {
        std::shared_lock lock{sync_table_mutex_};
        const auto it = sync_points_.find(sync_serial);
        if (it != sync_points_.end()) {
            return it->second;
        }
    } catch (...) {
    }
    return TimelineSyncPoint{};
}

bool SyncManager::ResolveQueueWaitSync(u64 sync_serial, u32 consumer_queue_id,
                                       VkSemaphoreSubmitInfo& out_wait_info,
                                       VkPipelineStageFlags2 dst_stage_mask) noexcept {
    out_wait_info = VkSemaphoreSubmitInfo{
        .sType = VK_STRUCTURE_TYPE_SEMAPHORE_SUBMIT_INFO,
        .pNext = nullptr,
        .semaphore = VK_NULL_HANDLE,
        .value = 0,
        .stageMask = dst_stage_mask,
        .deviceIndex = 0,
    };

    const TimelineSyncPoint point = FindSyncPoint(sync_serial);
    if (!point || point.queue_id >= kMaxNvnQueues) {
        return false;
    }

    // Same-queue stream order already guarantees producer commands retire before consumer commands.
    if (point.queue_id == consumer_queue_id) {
        same_queue_waits_elided_.fetch_add(1, std::memory_order_relaxed);
        return false;
    }

    // Elide cross-queue semaphore submission overhead if the producer tick already completed.
    if (IsTimelineValueComplete(point.queue_id, point.timeline_value)) {
        return false;
    }

    VkSemaphore producer_sem =
        queue_timelines_[point.queue_id].raw_handle.load(std::memory_order_acquire);
    if (producer_sem == VK_NULL_HANDLE) {
        try {
            producer_sem = QueueTimelineSemaphore(point.queue_id);
        } catch (...) {
            return false;
        }
        if (producer_sem == VK_NULL_HANDLE) {
            return false;
        }
    }

    out_wait_info.semaphore = producer_sem;
    out_wait_info.value = point.timeline_value;
    cross_queue_semaphore_waits_.fetch_add(1, std::memory_order_relaxed);
    return true;
}

SyncWaitStatus SyncManager::WaitSyncHost(u64 sync_serial, u64 timeout_ns) noexcept {
    const TimelineSyncPoint point = FindSyncPoint(sync_serial);
    if (!point || point.queue_id >= kMaxNvnQueues) {
        return SyncWaitStatus::Failed;
    }

    QueueTimelineSlot& slot = queue_timelines_[point.queue_id];

    // Step 1: O(1) user-space atomic check (~1 ns, zero driver calls on hit).
    if (slot.cached_completed_value.load(std::memory_order_acquire) >= point.timeline_value)
        [[likely]] {
        host_sync_fast_cache_hits_.fetch_add(1, std::memory_order_relaxed);
        return SyncWaitStatus::AlreadySignaled;
    }

    const VkSemaphore sem = slot.raw_handle.load(std::memory_order_acquire);
    if (sem == VK_NULL_HANDLE) {
        return SyncWaitStatus::Failed;
    }

    // Step 2: Single non-blocking counter poll via `vkGetSemaphoreCounterValue`.
    host_sync_driver_polls_.fetch_add(1, std::memory_order_relaxed);
    u64 live_value = 0;
    const VkResult poll_result =
        dld_.vkGetSemaphoreCounterValue(*device_.GetLogical(), sem, &live_value);
    if (poll_result != VK_SUCCESS) {
        return SyncWaitStatus::Failed;
    }
    MonotonicMaxStore(slot.cached_completed_value, live_value);
    if (live_value >= point.timeline_value) {
        return SyncWaitStatus::AlreadySignaled;
    }

    if (timeout_ns == 0) {
        return SyncWaitStatus::TimeoutExpired;
    }

    // Step 3: Sleep only the calling guest fiber in `vkWaitSemaphores` up to `timeout_ns`.
    host_sync_blocking_waits_.fetch_add(1, std::memory_order_relaxed);
    const VkSemaphoreWaitInfo wait_info{
        .sType = VK_STRUCTURE_TYPE_SEMAPHORE_WAIT_INFO,
        .pNext = nullptr,
        .flags = 0,
        .semaphoreCount = 1,
        .pSemaphores = &sem,
        .pValues = &point.timeline_value,
    };
    const VkResult wait_result =
        dld_.vkWaitSemaphores(*device_.GetLogical(), &wait_info, timeout_ns);
    if (wait_result == VK_SUCCESS) {
        MonotonicMaxStore(slot.cached_completed_value, point.timeline_value);
        return SyncWaitStatus::ConditionSatisfied;
    }
    if (wait_result == VK_TIMEOUT) {
        return SyncWaitStatus::TimeoutExpired;
    }
    return SyncWaitStatus::Failed;
}

