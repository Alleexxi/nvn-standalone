bool SyncManager::IsSupported(const Device& device) noexcept {
    if (!device.HasTimelineSemaphore() || !device.HasSynchronization2() ||
        !device.IsBufferDeviceAddressSupported() || !device.IsHostQueryResetSupported()) {
        return false;
    }

    const vk::DeviceDispatch& dld = device.GetDispatchLoader();
    if (dld.vkCreateSemaphore == nullptr || dld.vkGetSemaphoreCounterValue == nullptr ||
        dld.vkWaitSemaphores == nullptr || dld.vkQueueSubmit2 == nullptr ||
        dld.vkCmdCopyQueryPoolResults == nullptr || dld.vkResetQueryPool == nullptr) {
        return false;
    }

    VkPhysicalDeviceTimelineSemaphoreFeatures timeline_features{
        .sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_TIMELINE_SEMAPHORE_FEATURES,
        .pNext = nullptr,
        .timelineSemaphore = VK_FALSE,
    };
    VkPhysicalDeviceBufferDeviceAddressFeatures bda_features{
        .sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_BUFFER_DEVICE_ADDRESS_FEATURES,
        .pNext = &timeline_features,
        .bufferDeviceAddress = VK_FALSE,
        .bufferDeviceAddressCaptureReplay = VK_FALSE,
        .bufferDeviceAddressMultiDevice = VK_FALSE,
    };
    VkPhysicalDeviceHostQueryResetFeatures host_reset_features{
        .sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_HOST_QUERY_RESET_FEATURES,
        .pNext = &bda_features,
        .hostQueryReset = VK_FALSE,
    };
    VkPhysicalDeviceFeatures2 features2{
        .sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2,
        .pNext = &host_reset_features,
        .features = {},
    };
    device.GetPhysical().GetFeatures2(features2);

    if (timeline_features.timelineSemaphore == VK_FALSE ||
        bda_features.bufferDeviceAddress == VK_FALSE ||
        host_reset_features.hostQueryReset == VK_FALSE) {
        return false;
    }

    VkPhysicalDeviceTimelineSemaphoreProperties timeline_props{
        .sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_TIMELINE_SEMAPHORE_PROPERTIES,
        .pNext = nullptr,
        .maxTimelineSemaphoreValueDifference = 0,
    };
    VkPhysicalDeviceProperties2 props2{
        .sType = VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_PROPERTIES_2,
        .pNext = &timeline_props,
        .properties = {},
    };
    device.GetPhysical().GetProperties2(props2);

    const VkPhysicalDeviceLimits& limits = props2.properties.limits;
    if (timeline_props.maxTimelineSemaphoreValueDifference < kMinTimelineValueDifference) {
        return false;
    }
    if (limits.maxPushConstantsSize < sizeof(GpuQueryResolvePushConstants) ||
        limits.maxPerStageDescriptorStorageBuffers < 4) {
        return false;
    }

    return true;
}

SyncManager::SyncManager(const Device& device, MemoryPoolManager& mempool_manager,
                         VmaAllocator allocator, const SyncManagerConfig& config)
    : device_{device}, dld_{device.GetDispatchLoader()}, mempool_manager_{mempool_manager},
      config_{config} {
    if (allocator != VK_NULL_HANDLE) {
        allocator_ = allocator;
    } else {
        owned_allocator_ = device_.CreateThreadSafeAllocator();
        allocator_ = owned_allocator_;
    }

    const VkPhysicalDeviceProperties props = device_.GetPhysical().GetProperties();
    ComputeTimestampFixedPoint(static_cast<double>(props.limits.timestampPeriod),
                               tick_to_ns_mul_, tick_to_ns_shift_);

    u32 valid_bits = 64;
    const auto queue_families = device_.GetPhysical().GetQueueFamilyProperties();
    if (device_.GetGraphicsFamily() < queue_families.size()) {
        const u32 reported_bits = queue_families[device_.GetGraphicsFamily()].timestampValidBits;
        if (reported_bits > 0) {
            valid_bits = reported_bits;
        }
    }
    if (valid_bits >= 64) {
        timestamp_valid_bits_mask_hi_ = ~0u;
    } else if (valid_bits > 32) {
        timestamp_valid_bits_mask_hi_ = (1u << (valid_bits - 32u)) - 1u;
    } else {
        timestamp_valid_bits_mask_hi_ = 0u;
    }

    pending_resolve_ops_.reserve(kMaxResolveOpsPerBatch);
    active_chunks_.reserve(8);
    free_chunks_.reserve(8);
    sync_points_.reserve(1024);

    InitializeGpuQueryResources();
}

SyncManager::~SyncManager() {
    active_chunks_.clear();
    in_flight_chunks_.clear();
    free_chunks_.clear();

    resolve_pipeline_.reset();
    resolve_pipeline_layout_.reset();
    resolve_shader_module_.reset();
    resolve_descriptor_set_ = VK_NULL_HANDLE;
    resolve_descriptor_pool_.reset();
    resolve_set_layout_.reset();

    auto reset_buf = [](AllocatedInternalBuffer& buf) noexcept {
        buf.buffer.reset();
        buf.allocation = VK_NULL_HANDLE;
        buf.device_address = 0;
        buf.mapped = {};
    };
    reset_buf(predicate_ring_buffer_);
    reset_buf(resolve_ops_ring_buffer_);
    reset_buf(queue_accumulators_buffer_);
    reset_buf(raw_query_results_buffer_);

    for (QueueTimelineSlot& slot : queue_timelines_) {
        std::lock_guard lock{slot.create_mutex};
        slot.raw_handle.store(VK_NULL_HANDLE, std::memory_order_relaxed);
        slot.semaphore.reset();
    }

    if (owned_allocator_ != VK_NULL_HANDLE) {
        vmaDestroyAllocator(owned_allocator_);
        owned_allocator_ = VK_NULL_HANDLE;
    }
    allocator_ = VK_NULL_HANDLE;
}

