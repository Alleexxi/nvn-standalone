SyncManager::QueryPoolChunk& SyncManager::AcquireActiveQueryChunk(u32 queue_id) {
    const u32 clamped_queue = queue_id < kMaxNvnQueues ? queue_id : 0;

    for (size_t i = active_chunks_.size(); i > 0; --i) {
        QueryPoolChunk& candidate = active_chunks_[i - 1];
        if (candidate.owner_queue_id == clamped_queue &&
            candidate.occlusion_used < kQueriesPerPoolChunk &&
            candidate.timestamp_used < kQueriesPerPoolChunk) {
            return candidate;
        }
    }

    if (free_chunks_.empty()) {
        ReclaimCompletedQueryPools();
    }

    if (!free_chunks_.empty()) {
        QueryPoolChunk reused = std::move(free_chunks_.back());
        free_chunks_.pop_back();
        reused.occlusion_used = 0;
        reused.timestamp_used = 0;
        reused.occlusion_copied = 0;
        reused.timestamp_copied = 0;
        reused.owner_queue_id = clamped_queue;
        reused.retire_timeline_value = 0;
        active_chunks_.push_back(std::move(reused));
        return active_chunks_.back();
    }

    const vk::Device& logical = device_.GetLogical();
    QueryPoolChunk fresh{};
    fresh.occlusion_pool = logical.CreateQueryPool(VkQueryPoolCreateInfo{
        .sType = VK_STRUCTURE_TYPE_QUERY_POOL_CREATE_INFO,
        .pNext = nullptr,
        .flags = 0,
        .queryType = VK_QUERY_TYPE_OCCLUSION,
        .queryCount = kQueriesPerPoolChunk,
        .pipelineStatistics = 0,
    });
    fresh.timestamp_pool = logical.CreateQueryPool(VkQueryPoolCreateInfo{
        .sType = VK_STRUCTURE_TYPE_QUERY_POOL_CREATE_INFO,
        .pNext = nullptr,
        .flags = 0,
        .queryType = VK_QUERY_TYPE_TIMESTAMP,
        .queryCount = kQueriesPerPoolChunk,
        .pipelineStatistics = 0,
    });

    if (device_.IsHostQueryResetSupported()) {
        logical.ResetQueryPool(*fresh.occlusion_pool, 0, kQueriesPerPoolChunk);
        logical.ResetQueryPool(*fresh.timestamp_pool, 0, kQueriesPerPoolChunk);
    }

    fresh.owner_queue_id = clamped_queue;
    active_chunks_.push_back(std::move(fresh));
    return active_chunks_.back();
}

u32 SyncManager::AllocateRawQueryResultSlot() noexcept {
    const u32 slot = raw_result_write_cursor_ & (kRawQueryResultRingCapacity - 1u);
    ++raw_result_write_cursor_;
    return slot;
}

u32 SyncManager::AllocatePredicateSlot() noexcept {
    const u32 slot = predicate_ring_cursor_ & (kConditionalPredicateSlots - 1u);
    ++predicate_ring_cursor_;
    return slot;
}

void SyncManager::ReclaimCompletedQueryPools() noexcept {
    if (in_flight_chunks_.empty()) {
        return;
    }

    try {
        const vk::Device& logical = device_.GetLogical();
        const bool can_host_reset = device_.IsHostQueryResetSupported();

        auto it = in_flight_chunks_.begin();
        while (it != in_flight_chunks_.end()) {
            if (it->retire_timeline_value == 0 ||
                IsTimelineValueComplete(it->owner_queue_id, it->retire_timeline_value)) {
                if (can_host_reset) {
                    if (it->occlusion_used > 0 && it->occlusion_pool) {
                        logical.ResetQueryPool(*it->occlusion_pool, 0, it->occlusion_used);
                    }
                    if (it->timestamp_used > 0 && it->timestamp_pool) {
                        logical.ResetQueryPool(*it->timestamp_pool, 0, it->timestamp_used);
                    }
                }
                it->occlusion_used = 0;
                it->timestamp_used = 0;
                it->occlusion_copied = 0;
                it->timestamp_copied = 0;
                it->retire_timeline_value = 0;
                free_chunks_.push_back(std::move(*it));
                it = in_flight_chunks_.erase(it);
            } else {
                ++it;
            }
        }
    } catch (...) {
    }
}

void SyncManager::EnsureOcclusionQueryActive(vk::CommandBuffer cmd, u32 queue_id) {
    const u32 clamped_queue = queue_id < kMaxNvnQueues ? queue_id : 0;
    if (occlusion_query_open_) {
        if (open_occlusion_chunk_idx_ < active_chunks_.size() &&
            active_chunks_[open_occlusion_chunk_idx_].owner_queue_id == clamped_queue) [[likely]] {
            return;
        }
        const u32 prev_owner = open_occlusion_chunk_idx_ < active_chunks_.size()
                                   ? active_chunks_[open_occlusion_chunk_idx_].owner_queue_id
                                   : 0;
        CloseActiveOcclusionQuery(cmd, prev_owner);
    }

    QueryPoolChunk& chunk = AcquireActiveQueryChunk(clamped_queue);
    const u32 chunk_idx = static_cast<u32>(&chunk - active_chunks_.data());
    const u32 query_slot = chunk.occlusion_used++;
    const u32 raw_slot = AllocateRawQueryResultSlot();

    cmd.BeginQuery(*chunk.occlusion_pool, query_slot, VK_QUERY_CONTROL_PRECISE_BIT);
    occlusion_query_open_ = true;
    open_occlusion_chunk_idx_ = chunk_idx;
    open_occlusion_query_slot_ = query_slot;
    open_occlusion_raw_slot_ = raw_slot;
    occlusion_queries_recorded_.fetch_add(1, std::memory_order_relaxed);
}

void SyncManager::CloseActiveOcclusionQuery(vk::CommandBuffer cmd, u32 queue_id) {
    if (!occlusion_query_open_) {
        return;
    }

    const QueryPoolChunk& chunk = active_chunks_[open_occlusion_chunk_idx_];
    const u32 effective_queue = queue_id < kMaxNvnQueues ? queue_id : chunk.owner_queue_id;
    cmd.EndQuery(*chunk.occlusion_pool, open_occlusion_query_slot_);
    occlusion_query_open_ = false;

    pending_resolve_ops_.push_back(GpuQueryResolveOp{
        .opcode = static_cast<u32>(GpuQueryResolveOp::OpCode::AccumulateOcclusionQuery),
        .queue_id = effective_queue,
        .raw_occlusion_index = open_occlusion_raw_slot_,
        .raw_timestamp_index = ~0u,
        .dst_bda = 0,
        .aux_value_or_src_b = 0,
    });
}

void SyncManager::RecordResetCounter(vk::CommandBuffer cmd, u32 queue_id, u32 counter_type) {
    counter_resets_recorded_.fetch_add(1, std::memory_order_relaxed);
    if (counter_type != NvnCounterKind::kSamplesPassed || queue_id >= kMaxNvnQueues) {
        return;
    }

    if (occlusion_query_open_) {
        CloseActiveOcclusionQuery(cmd, queue_id);
    }

    // Coalesce back-to-back resets on the same queue in O(1).
    if (!pending_resolve_ops_.empty()) {
        const GpuQueryResolveOp& back = pending_resolve_ops_.back();
        if (back.opcode ==
                static_cast<u32>(GpuQueryResolveOp::OpCode::ResetOcclusionAccumulator) &&
            back.queue_id == queue_id) {
            return;
        }
    }

    pending_resolve_ops_.push_back(GpuQueryResolveOp{
        .opcode = static_cast<u32>(GpuQueryResolveOp::OpCode::ResetOcclusionAccumulator),
        .queue_id = queue_id,
        .raw_occlusion_index = ~0u,
        .raw_timestamp_index = ~0u,
        .dst_bda = 0,
        .aux_value_or_src_b = 0,
    });
}

bool SyncManager::RecordReportCounter(vk::CommandBuffer cmd, u32 queue_id, u32 counter_type,
                                      u64 guest_report_address) {
    if (queue_id >= kMaxNvnQueues) [[unlikely]] {
        return false;
    }

    const VkDeviceAddress dst_bda = mempool_manager_.ResolveDeviceAddress(
        guest_report_address, sizeof(VideoCommon::Nvn::NVNcounterData));
    if (dst_bda == 0 || (dst_bda & 3ULL) != 0) [[unlikely]] {
        return false;
    }

    if (counter_type == NvnCounterKind::kSamplesPassed) {
        if (occlusion_query_open_) {
            CloseActiveOcclusionQuery(cmd, queue_id);
        }

        QueryPoolChunk& chunk = AcquireActiveQueryChunk(queue_id);
        const u32 ts_slot = chunk.timestamp_used++;
        const u32 ts_raw_slot = AllocateRawQueryResultSlot();
        cmd.WriteTimestamp(VK_PIPELINE_STAGE_BOTTOM_OF_PIPE_BIT, *chunk.timestamp_pool, ts_slot);
        timestamp_queries_recorded_.fetch_add(1, std::memory_order_relaxed);

        pending_resolve_ops_.push_back(GpuQueryResolveOp{
            .opcode = static_cast<u32>(GpuQueryResolveOp::OpCode::WriteOcclusionReport),
            .queue_id = queue_id,
            .raw_occlusion_index = ~0u,
            .raw_timestamp_index = ts_raw_slot,
            .dst_bda = dst_bda,
            .aux_value_or_src_b = 0,
        });
        return true;
    }

    const VkPipelineStageFlagBits ts_stage =
        (counter_type == NvnCounterKind::kTimestampTop)
            ? VK_PIPELINE_STAGE_TOP_OF_PIPE_BIT
            : VK_PIPELINE_STAGE_BOTTOM_OF_PIPE_BIT;

    QueryPoolChunk& chunk = AcquireActiveQueryChunk(queue_id);
    const u32 ts_slot = chunk.timestamp_used++;
    const u32 ts_raw_slot = AllocateRawQueryResultSlot();
    cmd.WriteTimestamp(ts_stage, *chunk.timestamp_pool, ts_slot);
    timestamp_queries_recorded_.fetch_add(1, std::memory_order_relaxed);

    pending_resolve_ops_.push_back(GpuQueryResolveOp{
        .opcode = static_cast<u32>(GpuQueryResolveOp::OpCode::WriteTimestampReport),
        .queue_id = queue_id,
        .raw_occlusion_index = ~0u,
        .raw_timestamp_index = ts_raw_slot,
        .dst_bda = dst_bda,
        .aux_value_or_src_b = 0,
    });
    return true;
}

bool SyncManager::RecordReportValue(vk::CommandBuffer cmd, u32 queue_id, u64 guest_report_address,
                                    u64 immediate_value) {
    if (queue_id >= kMaxNvnQueues) [[unlikely]] {
        return false;
    }

    const VkDeviceAddress dst_bda = mempool_manager_.ResolveDeviceAddress(
        guest_report_address, sizeof(VideoCommon::Nvn::NVNcounterData));
    if (dst_bda == 0 || (dst_bda & 3ULL) != 0) [[unlikely]] {
        return false;
    }

    QueryPoolChunk& chunk = AcquireActiveQueryChunk(queue_id);
    const u32 ts_slot = chunk.timestamp_used++;
    const u32 ts_raw_slot = AllocateRawQueryResultSlot();
    cmd.WriteTimestamp(VK_PIPELINE_STAGE_BOTTOM_OF_PIPE_BIT, *chunk.timestamp_pool, ts_slot);
    timestamp_queries_recorded_.fetch_add(1, std::memory_order_relaxed);

    pending_resolve_ops_.push_back(GpuQueryResolveOp{
        .opcode = static_cast<u32>(GpuQueryResolveOp::OpCode::WriteImmediateValue),
        .queue_id = queue_id,
        .raw_occlusion_index = ~0u,
        .raw_timestamp_index = ts_raw_slot,
        .dst_bda = dst_bda,
        .aux_value_or_src_b = immediate_value,
    });
    return true;
}

u32 SyncManager::FlushQueryResolves(vk::CommandBuffer cmd, PassManager* pass_manager,
                                    u32 submit_queue_id, u64 retire_timeline_value) {
    // Close any open in-pass occlusion query before ending Dynamic Rendering.
    if (occlusion_query_open_) {
        const u32 owner_q = open_occlusion_chunk_idx_ < active_chunks_.size()
                                ? active_chunks_[open_occlusion_chunk_idx_].owner_queue_id
                                : submit_queue_id;
        CloseActiveOcclusionQuery(cmd, owner_q);
    }

    const auto retire_active_chunks = [&]() {
        if (retire_timeline_value == 0 || active_chunks_.empty()) {
            return;
        }
        const u32 safe_submit_queue = submit_queue_id < kMaxNvnQueues ? submit_queue_id : 0;
        for (QueryPoolChunk& chunk : active_chunks_) {
            if (chunk.occlusion_used > 0 || chunk.timestamp_used > 0) {
                chunk.owner_queue_id = safe_submit_queue;
                chunk.retire_timeline_value = retire_timeline_value;
                in_flight_chunks_.push_back(std::move(chunk));
            } else {
                free_chunks_.push_back(std::move(chunk));
            }
        }
        active_chunks_.clear();
    };

    if (pending_resolve_ops_.empty()) {
        retire_active_chunks();
        return 0;
    }

    if (pass_manager != nullptr && pass_manager->IsRenderingActive()) {
        pass_manager->EndRendering(cmd);
    }

    if (!resolve_pipeline_ || resolve_ops_ring_buffer_.mapped.empty() ||
        !raw_query_results_buffer_.buffer) {
        pending_resolve_ops_.clear();
        retire_active_chunks();
        return 0;
    }

    // Stream all uncopied raw 64-bit hardware query results into `raw_query_results_buffer_`
    // using linear-stride run coalescing (typically 1 copy for occlusion + 1 copy for timestamps).
    CopyRunEmitter occ_emitter{.cmd = cmd, .dst_buffer = *raw_query_results_buffer_.buffer};
    CopyRunEmitter ts_emitter{.cmd = cmd, .dst_buffer = *raw_query_results_buffer_.buffer};
    std::array<u32, kMaxNvnQueues> occ_chunk_cursor{};
    std::array<u32, kMaxNvnQueues> ts_chunk_cursor{};

    for (const GpuQueryResolveOp& op : pending_resolve_ops_) {
        if (op.raw_occlusion_index != ~0u && op.queue_id < kMaxNvnQueues) {
            u32& idx = occ_chunk_cursor[op.queue_id];
            while (idx < active_chunks_.size() &&
                   (active_chunks_[idx].owner_queue_id != op.queue_id ||
                    active_chunks_[idx].occlusion_copied >= active_chunks_[idx].occlusion_used)) {
                ++idx;
            }
            if (idx < active_chunks_.size()) {
                QueryPoolChunk& chunk = active_chunks_[idx];
                occ_emitter.Push(*chunk.occlusion_pool, chunk.occlusion_copied++,
                                 op.raw_occlusion_index);
            }
        }
        if (op.raw_timestamp_index != ~0u && op.queue_id < kMaxNvnQueues) {
            u32& idx = ts_chunk_cursor[op.queue_id];
            while (idx < active_chunks_.size() &&
                   (active_chunks_[idx].owner_queue_id != op.queue_id ||
                    active_chunks_[idx].timestamp_copied >= active_chunks_[idx].timestamp_used)) {
                ++idx;
            }
            if (idx < active_chunks_.size()) {
                QueryPoolChunk& chunk = active_chunks_[idx];
                ts_emitter.Push(*chunk.timestamp_pool, chunk.timestamp_copied++,
                                op.raw_timestamp_index);
            }
        }
    }
    occ_emitter.Flush();
    ts_emitter.Flush();

    EmitMemoryBarrier2(
        cmd, dld_,
        VK_PIPELINE_STAGE_2_TRANSFER_BIT | VK_PIPELINE_STAGE_2_COMPUTE_SHADER_BIT |
            VK_PIPELINE_STAGE_2_HOST_BIT,
        VK_ACCESS_2_TRANSFER_WRITE_BIT | VK_ACCESS_2_SHADER_WRITE_BIT | VK_ACCESS_2_HOST_WRITE_BIT,
        VK_PIPELINE_STAGE_2_COMPUTE_SHADER_BIT,
        VK_ACCESS_2_SHADER_READ_BIT | VK_ACCESS_2_SHADER_WRITE_BIT);

    cmd.BindPipeline(VK_PIPELINE_BIND_POINT_COMPUTE, *resolve_pipeline_);
    cmd.BindDescriptorSets(VK_PIPELINE_BIND_POINT_COMPUTE, *resolve_pipeline_layout_, 0,
                           resolve_descriptor_set_, {});

    const u32 total_ops = static_cast<u32>(pending_resolve_ops_.size());
    const u64 clock_offset_ns = guest_clock_offset_ns_.load(std::memory_order_relaxed);
    const bool ops_ring_coherent = resolve_ops_ring_buffer_.buffer.IsHostCoherent();

    u32 cursor = 0;
    while (cursor < total_ops) {
        const u32 batch_count = (std::min)(total_ops - cursor, kMaxResolveOpsPerBatch);
        if (resolve_op_ring_cursor_ + batch_count > kQueryResolveRingCapacity) {
            resolve_op_ring_cursor_ = 0;
        }
        const u32 ring_begin = resolve_op_ring_cursor_;
        resolve_op_ring_cursor_ += batch_count;

        const size_t dst_byte_offset = static_cast<size_t>(ring_begin) * sizeof(GpuQueryResolveOp);
        const size_t copy_bytes = static_cast<size_t>(batch_count) * sizeof(GpuQueryResolveOp);
        std::memcpy(resolve_ops_ring_buffer_.mapped.data() + dst_byte_offset,
                    pending_resolve_ops_.data() + cursor, copy_bytes);
        if (!ops_ring_coherent) {
            vmaFlushAllocation(allocator_, resolve_ops_ring_buffer_.allocation, dst_byte_offset,
                               copy_bytes);
        }

        const GpuQueryResolvePushConstants pc{
            .op_begin_index = ring_begin,
            .op_count = batch_count,
            .tick_to_ns_mul = tick_to_ns_mul_,
            .guest_clock_offset_ns = clock_offset_ns,
            .tick_to_ns_shift = tick_to_ns_shift_,
            .timestamp_valid_bits_mask_hi = timestamp_valid_bits_mask_hi_,
        };
        cmd.PushConstants(*resolve_pipeline_layout_, VK_SHADER_STAGE_COMPUTE_BIT, pc);
        cmd.Dispatch(1, 1, 1);
        compute_resolve_dispatches_.fetch_add(1, std::memory_order_relaxed);

        cursor += batch_count;
        if (cursor < total_ops) {
            // Serialize accumulator state across multi-batch flushes (> 4096 ops).
            EmitMemoryBarrier2(cmd, dld_, VK_PIPELINE_STAGE_2_COMPUTE_SHADER_BIT,
                               VK_ACCESS_2_SHADER_WRITE_BIT,
                               VK_PIPELINE_STAGE_2_COMPUTE_SHADER_BIT,
                               VK_ACCESS_2_SHADER_READ_BIT | VK_ACCESS_2_SHADER_WRITE_BIT);
        }
    }

    VkPipelineStageFlags2 dst_stages =
        VK_PIPELINE_STAGE_2_ALL_COMMANDS_BIT | VK_PIPELINE_STAGE_2_HOST_BIT;
    VkAccessFlags2 dst_access =
        VK_ACCESS_2_MEMORY_READ_BIT | VK_ACCESS_2_MEMORY_WRITE_BIT | VK_ACCESS_2_HOST_READ_BIT;
    if (device_.IsExtConditionalRendering()) {
        dst_stages |= VK_PIPELINE_STAGE_2_CONDITIONAL_RENDERING_BIT_EXT;
        dst_access |= VK_ACCESS_2_CONDITIONAL_RENDERING_READ_BIT_EXT;
    }
    EmitMemoryBarrier2(cmd, dld_, VK_PIPELINE_STAGE_2_COMPUTE_SHADER_BIT,
                       VK_ACCESS_2_SHADER_WRITE_BIT, dst_stages, dst_access);

    pending_resolve_ops_.clear();
    retire_active_chunks();
    return total_ops;
}

// ================================================================================================
// GPU Conditional Rendering (`VK_EXT_conditional_rendering`)
// ================================================================================================

bool SyncManager::BeginConditionalRendering(vk::CommandBuffer cmd, PassManager* pass_manager,
                                            u64 guest_counter_pair_address, u32 condition_mode) {
    // Close any open in-pass occlusion query before leaving the active rendering scope.
    if (occlusion_query_open_) {
        const u32 owner_q = open_occlusion_chunk_idx_ < active_chunks_.size()
                                ? active_chunks_[open_occlusion_chunk_idx_].owner_queue_id
                                : 0;
        CloseActiveOcclusionQuery(cmd, owner_q);
    }

    // End active Dynamic Rendering BEFORE ending/beginning outer conditional rendering scope so
    // `vkCmdBeginConditionalRenderingEXT` and `vkCmdEndConditionalRenderingEXT` both execute
    // outside render pass instances (satisfying VUID-vkCmdEndConditionalRenderingEXT-None-01986).
    if (pass_manager != nullptr && pass_manager->IsRenderingActive()) {
        pass_manager->EndRendering(cmd);
    }

    if (conditional_rendering_active_) {
        EndConditionalRendering(cmd);
    }

    if (!config_.enable_conditional_rendering || !device_.IsExtConditionalRendering() ||
        dld_.vkCmdBeginConditionalRenderingEXT == nullptr || !resolve_pipeline_ ||
        !predicate_ring_buffer_.buffer) {
        return false;
    }

    const VkDeviceAddress src_a_bda =
        mempool_manager_.ResolveDeviceAddress(guest_counter_pair_address, sizeof(u64));
    const VkDeviceAddress src_b_bda =
        mempool_manager_.ResolveDeviceAddress(guest_counter_pair_address + 16ULL, sizeof(u64));
    if (src_a_bda == 0 || src_b_bda == 0 || (src_a_bda & 3ULL) != 0 ||
        (src_b_bda & 3ULL) != 0) [[unlikely]] {
        return false;
    }

    const u32 predicate_slot = AllocatePredicateSlot();
    const auto opcode = (condition_mode == NvnConditionMode::kRenderIfNotEqual)
                            ? GpuQueryResolveOp::OpCode::EvaluateConditionNotEqual
                            : GpuQueryResolveOp::OpCode::EvaluateConditionEqual;

    pending_resolve_ops_.push_back(GpuQueryResolveOp{
        .opcode = static_cast<u32>(opcode),
        .queue_id = predicate_slot,
        .raw_occlusion_index = ~0u,
        .raw_timestamp_index = ~0u,
        .dst_bda = src_a_bda,
        .aux_value_or_src_b = src_b_bda,
    });
    gpu_conditions_evaluated_.fetch_add(1, std::memory_order_relaxed);

    (void)FlushQueryResolves(cmd, pass_manager, 0, 0);

    const VkConditionalRenderingBeginInfoEXT begin_info{
        .sType = VK_STRUCTURE_TYPE_CONDITIONAL_RENDERING_BEGIN_INFO_EXT,
        .pNext = nullptr,
        .buffer = *predicate_ring_buffer_.buffer,
        .offset = static_cast<VkDeviceSize>(predicate_slot) * kPredicateSlotStrideBytes,
        .flags = 0,
    };
    cmd.BeginConditionalRenderingEXT(begin_info);
    conditional_rendering_active_ = true;
    return true;
}

void SyncManager::EndConditionalRendering(vk::CommandBuffer cmd) noexcept {
    if (!conditional_rendering_active_) {
        return;
    }
    conditional_rendering_active_ = false;
    if (dld_.vkCmdEndConditionalRenderingEXT != nullptr) {
        cmd.EndConditionalRenderingEXT();
    }
}

