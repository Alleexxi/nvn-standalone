void SyncManager::RecordSignalEvent(vk::CommandBuffer cmd, u32 queue_id, u64 timeline_val,
                                    u64 guest_event_address, u32 signal_mode, u32 value) {
    if (queue_id < kMaxNvnQueues && guest_event_address != 0 && timeline_val != 0) {
        (void)QueueTimelineSemaphore(queue_id);
        std::unique_lock lock{sync_table_mutex_};
        sync_points_[guest_event_address] = TimelineSyncPoint{
            .queue_id = queue_id,
            .timeline_value = timeline_val,
            .condition = signal_mode,
            .flags = value,
            .valid = true,
        };
    }

    const BufferRangeView view = mempool_manager_.ResolveBufferRange(guest_event_address, sizeof(u32));
    if (!view) {
        LOG_WARNING(Render_Vulkan,
                    "[NvnClean] RecordSignalEvent: unmapped guest event address {:#x}",
                    guest_event_address);
        return;
    }

    // Ensure any queued counter/value reports on this stream complete before signaling the event.
    if (HasPendingQueryResolves()) {
        (void)FlushQueryResolves(cmd, nullptr, queue_id, 0);
    }

    if (signal_mode == kNvnEventSignalWrite && (view.offset & 3ULL) == 0) {
        EmitMemoryBarrier2(cmd, dld_, VK_PIPELINE_STAGE_2_ALL_COMMANDS_BIT,
                           VK_ACCESS_2_MEMORY_WRITE_BIT, VK_PIPELINE_STAGE_2_TRANSFER_BIT,
                           VK_ACCESS_2_TRANSFER_WRITE_BIT);
        cmd.FillBuffer(view.buffer, view.offset, sizeof(u32), value);
        EmitMemoryBarrier2(cmd, dld_, VK_PIPELINE_STAGE_2_TRANSFER_BIT,
                           VK_ACCESS_2_TRANSFER_WRITE_BIT,
                           VK_PIPELINE_STAGE_2_ALL_COMMANDS_BIT | VK_PIPELINE_STAGE_2_HOST_BIT,
                           VK_ACCESS_2_MEMORY_READ_BIT | VK_ACCESS_2_MEMORY_WRITE_BIT |
                               VK_ACCESS_2_HOST_READ_BIT);
        return;
    }

    if (!resolve_pipeline_ || resolve_ops_ring_buffer_.mapped.empty() ||
        view.device_address == 0 || (view.device_address & 3ULL) != 0) {
        return;
    }

    if (resolve_op_ring_cursor_ >= kQueryResolveRingCapacity) {
        resolve_op_ring_cursor_ = 0;
    }
    const u32 op_slot = resolve_op_ring_cursor_++;
    const GpuQueryResolveOp event_op{
        .opcode = (signal_mode == kNvnEventSignalWrite) ? kInternalOpSignalEventWrite32
                                                        : kInternalOpSignalEventAdd32,
        .queue_id = queue_id,
        .raw_occlusion_index = ~0u,
        .raw_timestamp_index = ~0u,
        .dst_bda = view.device_address,
        .aux_value_or_src_b = value,
    };

    const size_t byte_offset = static_cast<size_t>(op_slot) * sizeof(GpuQueryResolveOp);
    std::memcpy(resolve_ops_ring_buffer_.mapped.data() + byte_offset, &event_op,
                sizeof(GpuQueryResolveOp));
    if (!resolve_ops_ring_buffer_.buffer.IsHostCoherent()) {
        vmaFlushAllocation(allocator_, resolve_ops_ring_buffer_.allocation, byte_offset,
                           sizeof(GpuQueryResolveOp));
    }

    EmitMemoryBarrier2(
        cmd, dld_, VK_PIPELINE_STAGE_2_ALL_COMMANDS_BIT | VK_PIPELINE_STAGE_2_HOST_BIT,
        VK_ACCESS_2_MEMORY_WRITE_BIT | VK_ACCESS_2_HOST_WRITE_BIT,
        VK_PIPELINE_STAGE_2_COMPUTE_SHADER_BIT,
        VK_ACCESS_2_SHADER_READ_BIT | VK_ACCESS_2_SHADER_WRITE_BIT);

    const GpuQueryResolvePushConstants pc{
        .op_begin_index = op_slot,
        .op_count = 1,
        .tick_to_ns_mul = tick_to_ns_mul_,
        .guest_clock_offset_ns = guest_clock_offset_ns_.load(std::memory_order_relaxed),
        .tick_to_ns_shift = tick_to_ns_shift_,
        .timestamp_valid_bits_mask_hi = timestamp_valid_bits_mask_hi_,
    };
    cmd.BindPipeline(VK_PIPELINE_BIND_POINT_COMPUTE, *resolve_pipeline_);
    cmd.BindDescriptorSets(VK_PIPELINE_BIND_POINT_COMPUTE, *resolve_pipeline_layout_, 0,
                           resolve_descriptor_set_, {});
    cmd.PushConstants(*resolve_pipeline_layout_, VK_SHADER_STAGE_COMPUTE_BIT, pc);
    cmd.Dispatch(1, 1, 1);
    compute_resolve_dispatches_.fetch_add(1, std::memory_order_relaxed);

    EmitMemoryBarrier2(cmd, dld_, VK_PIPELINE_STAGE_2_COMPUTE_SHADER_BIT,
                       VK_ACCESS_2_SHADER_WRITE_BIT,
                       VK_PIPELINE_STAGE_2_ALL_COMMANDS_BIT | VK_PIPELINE_STAGE_2_HOST_BIT,
                       VK_ACCESS_2_MEMORY_READ_BIT | VK_ACCESS_2_MEMORY_WRITE_BIT |
                           VK_ACCESS_2_HOST_READ_BIT);
}

